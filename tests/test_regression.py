@pytest.mark.regression
def test_ccbhash_digest(finfo, zignature, first_func_cfg, global_call_graph):
    """CCBHash digest matches the pinned value."""
    features = CCBHashBuilder.build(finfo, zignature, first_func_cfg, global_call_graph)
    assert isinstance(features, CCBHashFeatures)
    assert str(features.ccbhash) == _CCBHASH


@pytest.mark.regression
def test_ccbhash_digest_length(finfo, zignature, first_func_cfg, global_call_graph):
    """CCBHash digest length equals sum of SUBHASH_SIZES (values are in nibbles)."""
    features = CCBHashBuilder.build(finfo, zignature, first_func_cfg, global_call_graph)
    digest_str = str(features.ccbhash)
    assert len(digest_str) == sum(SUBHASH_SIZES.values())
    assert all(c in "0123456789ABCDEFabcdef" for c in digest_str)


@pytest.mark.regression
def test_ccbhash_is_deterministic(finfo, zignature, first_func_cfg, global_call_graph):
    """CCBHashBuilder.build() is deterministic."""
    a = CCBHashBuilder.build(finfo, zignature, first_func_cfg, global_call_graph)
    b = CCBHashBuilder.build(finfo, zignature, first_func_cfg, global_call_graph)
    assert str(a.ccbhash) == str(b.ccbhash)


