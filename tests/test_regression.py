# FSS (Marcelli) — Cisco-Talos cross-validation
#
# Input: function at address 0x7b0 in hello.i64, extracted by the Cisco-Talos
#   IDA_fss pipeline and serialised to:
#   Models/functionsimsearch/IDA_fss/testdata/hello_Capstone_True_fss.json
