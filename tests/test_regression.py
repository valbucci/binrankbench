"""Regression tests for binary similarity strategy implementations.

PURPOSE
-------
These tests compute hashes / feature strings for each strategy using the
canonical test binary ``git_2-47-1.exe`` and assert exact digest values.

If a test fails after a code change the implementation has been altered in a
way that changes its output — this must be explicitly reviewed and the expected
digest updated in this file with a comment explaining why it changed.

REVIEWER GUIDANCE
-----------------
* Each test section maps 1-to-1 to one strategy implementation file.
* The pinned digests at the top of each section are the ground truth for the
  current implementation.  Changing them requires a deliberate decision.
* Run only regression tests:   pytest -m regression
* Skip regression tests:       pytest -m "not regression"

EXTERNAL VALIDATION SOURCES
----------------------------
FSS (Marcelli):
  Input function features — Cisco-Talos binary_function_similarity repo:
    Models/functionsimsearch/IDA_fss/testdata/hello_Capstone_True_fss.json
  Expected hash values — same repo:
    Models/functionsimsearch/testdata/fss_csvs/<weight-config>.csv

Machoke (synthetic cases):
  The README-based test (test_machoke.py) is the only externally-verifiable
  ground truth: https://github.com/conix-security/machoke/blob/master/README.md
  The additional synthetic cases below are determinism checks generated by this
  implementation. External validation against the original machoke.py is not
  possible: the original uses r2pipe with an old radare2 instruction-type
  vocabulary incompatible with radare2 v6.0.4.
"""

