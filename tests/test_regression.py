# Expected hash values: taken verbatim from the four weight-config CSV files in
#   Models/functionsimsearch/testdata/fss_csvs/<IMM:…_MNEM:…_GRAPH:…>.csv
#   Columns used: hashes0 (first 64 bits) and hashes1 (second 64 bits).
# ---------------------------------------------------------------------------

# Raw function components from hello_Capstone_True_fss.json → address 0x7b0
_HELLO_NODES = [1991, 2024, 1968, 2003, 2008, 1977]
_HELLO_EDGES = [
    [1977, 2003], [1968, 2024], [1977, 1991],
    [2003, 2008], [1991, 2003], [1968, 1977],
]
_HELLO_INSTRUCTIONS = {
    "1991": [["mov", ["rdi", "[rip+2099258]"]], ["call", ["#0x6e0"]]],
    "2024": [["ret", []]],
    "1968": [["cmp", ["[rip+2099577]", "#0x0"]], ["jne", ["#0x7e8"]]],
    "2003": [["call", ["#0x720"]]],
    "2008": [["mov", ["[rip+2099537]", "#0x1"]], ["pop", ["rbp"]], ["ret", []]],
    "1977": [["cmp", ["[rip+2099215]", "#0x0"]], ["push", ["rbp"]],
             ["mov", ["rbp", "rsp"]], ["je", ["#0x7d3"]]],
}

# (hashes0, hashes1) pairs from each CSV file
_HELLO_FSS = {
    # IMM:0.00_MNEM:0.00_GRAPH:1.00.csv
    "imm0_mnem0_graph1": (352327471521789799,  11404745248164153396),
    # IMM:0.00_MNEM:1.00_GRAPH:1.00.csv
    "imm0_mnem1_graph1": (495719160268181542,  2180286927064795196),
    # IMM:1.00_MNEM:1.00_GRAPH:1.00.csv — adding immediates at weight 1.0
    # does not change the hash for this particular function's operand set
    "imm1_mnem1_graph1": (495719160268181542,  2180286927064795196),
    # IMM:4.00_MNEM:0.05_GRAPH:1.00.csv
    "imm4_mnem005_graph1": (352166939326083367, 2181373211309115444),
}

_HELLO_WEIGHTS = {
    "imm0_mnem0_graph1":   {"immediate_weight": 0.00, "mnem_weight": 0.00, "graphlet_weight": 1.00},
    "imm0_mnem1_graph1":   {"immediate_weight": 0.00, "mnem_weight": 1.00, "graphlet_weight": 1.00},
    "imm1_mnem1_graph1":   {"immediate_weight": 1.00, "mnem_weight": 1.00, "graphlet_weight": 1.00},
    "imm4_mnem005_graph1": {"immediate_weight": 4.00, "mnem_weight": 0.05, "graphlet_weight": 1.00},
}


@pytest.mark.regression
@pytest.mark.parametrize("config", list(_HELLO_FSS.keys()))
def test_fss_marcelli_cisco_talos(config):
    """FSS (Marcelli) matches the Cisco-Talos reference output for hello.i64:0x7b0.

    Input features are from hello_Capstone_True_fss.json; expected hashes are
    from the fss_csvs/<config>.csv files in the Cisco-Talos
    binary_function_similarity repository.
    """
    pytest.importorskip("functionsimsearch")
    from binrankbench.modules.fss import FunctionSimSearch
    expected = FunctionSimSearch(*_HELLO_FSS[config])
    result = FunctionSimSearch.from_components(
        _HELLO_NODES, _HELLO_EDGES, _HELLO_INSTRUCTIONS,
        mode="marcelli", marcelli_weights=_HELLO_WEIGHTS[config],
    )
    assert result == expected, (
        f"Config {config}: got {result.first},{result.second} "
        f"expected {expected.first},{expected.second}"
    )


